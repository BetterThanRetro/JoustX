using System.Text;
using System.Text.RegularExpressions;
using Joust.Assembler;
using Joust.Emulation;
using Joust.Port.Translated;

namespace Joust.Tools;

/// <summary>
/// Translates the sound board's 6808 program (VSNDRM4.ASM) to C# (Sound.g.cs), as
/// <see cref="Translator"/> does for the main board: one <c>case</c> per instruction, with its
/// source line, its cycles (measured on the reference 6800 core) and the same flag code
/// (<see cref="Alu6800"/>). Each instruction first checks <see cref="SoundBoard.Due"/> and
/// charges its cycles through <see cref="SoundBoard.Spend"/>.
/// </summary>
internal sealed partial class SoundTranslator
{
    private sealed class Insn
    {
        public int Pc, Length, Cycles;
        public bool FallsThrough = true;
        public string Text = "";
        public string? Undefined;
        public readonly List<string> Body = [];
        public readonly List<int> Targets = [];
    }

    private sealed record UnitPlan(string Name, string Method, List<Insn> Insns);

    private readonly byte[] _mem;
    private readonly AssemblyResult _program;
    private readonly SortedDictionary<int, Insn> _insns = [];
    private readonly Dictionary<int, string> _labels;
    private readonly List<UnitPlan> _units = [];

    public SoundTranslator(AssemblyResult program)
    {
        _program = program;
        _mem = program.Memory;
        var work = new Stack<(int Pc, int From)>();
        foreach (int pc in program.Instructions.Keys.Where(InRom).OrderByDescending(a => a))
            work.Push((pc, -1));
        while (work.Count > 0)
        {
            var (pc, from) = work.Pop();
            if (_insns.ContainsKey(pc)) continue;
            var d = Decode(pc);
            d.Text = program.Instructions.TryGetValue(pc, out var line)
                ? $"{TranslationText.Squash(line.Text)}  ({line.File}:{line.Line})"
                : $"(reached from ${from:X4}; not in the listing)";
            _insns[pc] = d;
            foreach (int target in d.Targets.Append(d.FallsThrough ? (pc + d.Length) & 0xFFFF : -1))
                if (target >= 0 && InRom(target) && !_insns.ContainsKey(target))
                    work.Push((target, pc));
        }
        _labels = TranslationText.Labels(program.Symbols, _insns.ContainsKey);
        foreach (var (name, insns) in TranslationText.Routines(_insns.Values, d => d.Pc, d => d.Length, _labels, "SOUND"))
            _units.Add(new UnitPlan(name, $"S{insns[0].Pc:X4}_{TranslationText.Identifier(name)}", insns));
    }

    private static bool InRom(int a) => a >= JoustRomBuild.SoundRomBase + 1;     // $F000 is the checksum byte

    public void Write(string outDir)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// The sound board's 6808 program (joust-main-asm/VSNDRM4.ASM) translated by \"joust-tools translate\".");
        sb.AppendLine("// Do not edit: change the translator and run it again.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("#pragma warning disable CS0162, CS0164, CS0168, CS0219");
        sb.AppendLine("using Joust.Emulation;");
        sb.AppendLine("using static Joust.Emulation.Alu6800;");
        sb.AppendLine();
        sb.AppendLine("namespace Joust.Port.Translated;");
        sb.AppendLine();
        sb.AppendLine("internal static class SoundCode");
        sb.AppendLine("{");
        sb.AppendLine($"    internal const ulong ImageHash = 0x{SoundTranslation.ImageHash(_mem):X16}UL;");
        sb.AppendLine();
        sb.AppendLine("    internal static readonly SoundUnit[] Units =");
        sb.AppendLine("    [");
        foreach (var unit in _units)
            sb.AppendLine($"        new(\"{unit.Name}\", {unit.Method}, [{string.Join(", ", unit.Insns.Select(d => $"0x{d.Pc:X4}"))}]),");
        sb.AppendLine("    ];");
        sb.AppendLine();
        foreach (var unit in _units)
            WriteUnit(sb, unit);
        sb.AppendLine("}");
        File.WriteAllText(Path.Combine(outDir, "Sound.g.cs"), sb.ToString());
    }

    private void WriteUnit(StringBuilder sb, UnitPlan unit)
    {
        var members = unit.Insns.Select(d => d.Pc).ToHashSet();
        sb.AppendLine($"    private static ushort {unit.Method}(SoundBoard b, ushort pc)");
        sb.AppendLine("    {");
        sb.AppendLine("        var c = b.Cpu;");
        sb.AppendLine("        int ea;");
        sb.AppendLine("        switch (pc)");
        sb.AppendLine("        {");
        foreach (var d in unit.Insns)
        {
            if (_labels.TryGetValue(d.Pc, out string? label) && d != unit.Insns[0])
                sb.AppendLine($"            // {label}:");
            sb.AppendLine($"            case 0x{d.Pc:X4}: // {d.Text}");
            if (d.Undefined != null)
            {
                sb.AppendLine($"                throw new InvalidOperationException(\"{d.Undefined}\");");
                continue;
            }
            sb.AppendLine($"                if (b.Due) return 0x{d.Pc:X4};");
            sb.AppendLine($"                b.Spend({d.Cycles});");
            var body = d.FallsThrough ? d.Body.Append(TranslationText.Go(d.Pc + d.Length)) : d.Body;
            foreach (string line in body)
                sb.AppendLine("                " + TranslationText.Resolve(line, members));
        }
        sb.AppendLine("        }");
        sb.AppendLine("        return pc;");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    public string Report() =>
        $"sound board: {_insns.Count} instructions ({_insns.Keys.Count(_program.Instructions.ContainsKey)} from the listing) in {_units.Count} routines, " +
        $"{_insns.Values.Count(d => d.Undefined != null)} undefined opcodes (they throw, as on the emulated core)";

    // ------------------------------------------------------------------ decoding

    private Insn Decode(int pc)
    {
        var d = new Insn { Pc = pc };
        byte B(int i) => _mem[(pc + i) & 0xFFFF];
        int W(int i) => (B(i) << 8) | B(i + 1);
        void E(string s) => d.Body.Add(s);
        string GoTo(int target) { d.Targets.Add(target & 0xFFFF); return TranslationText.Go(target); }

        byte op = B(0);
        int next() => (pc + d.Length) & 0xFFFF;
        try
        {
            d.Cycles = new Cpu6800(new ImageBus(_mem)) { PC = (ushort)pc }.Step();
        }
        catch (InvalidOperationException)
        {
            d.Undefined = $"undefined 6800 opcode ${op:X2} at ${pc:X4}";
            d.Length = 1;
            d.FallsThrough = false;
            return d;
        }

        d.Length = 1;
        switch (op)
        {
            case 0x01: return d;                                                 // NOP
            case 0x06: E("c.CC = (byte)(c.A | 0xC0);"); return d;               // TAP
            case 0x07: E("c.A = c.CC;"); return d;                               // TPA
            case 0x08: E("c.X++; Flag(ref c.CC, Z, c.X == 0);"); return d;       // INX
            case 0x09: E("c.X--; Flag(ref c.CC, Z, c.X == 0);"); return d;       // DEX
            case 0x0A: E("c.CC &= 0xFD;"); return d;                             // CLV
            case 0x0B: E("c.CC |= 0x02;"); return d;                             // SEV
            case 0x0C: E("c.CC &= 0xFE;"); return d;                             // CLC
            case 0x0D: E("c.CC |= 0x01;"); return d;                             // SEC
            case 0x0E: E("c.CC &= 0xEF;"); return d;                             // CLI
            case 0x0F: E("c.CC |= 0x10;"); return d;                             // SEI
            case 0x10: E("c.A = Sub(ref c.CC, c.A, c.B, false);"); return d;     // SBA
            case 0x11: E("Sub(ref c.CC, c.A, c.B, false);"); return d;           // CBA
            case 0x16: E("c.B = c.A; Logic(ref c.CC, c.B);"); return d;          // TAB
            case 0x17: E("c.A = c.B; Logic(ref c.CC, c.A);"); return d;          // TBA
            case 0x19: E("c.A = Daa(ref c.CC, c.A);"); return d;
            case 0x1B: E("c.A = Add(ref c.CC, c.A, c.B, false);"); return d;     // ABA
            case 0x30: E("c.X = (ushort)(c.SP + 1);"); return d;                 // TSX
            case 0x31: E("c.SP++;"); return d;                                   // INS
            case 0x32: E("c.A = b.Pull();"); return d;
            case 0x33: E("c.B = b.Pull();"); return d;
            case 0x34: E("c.SP--;"); return d;                                   // DES
            case 0x35: E("c.SP = (ushort)(c.X - 1);"); return d;                 // TXS
            case 0x36: E("b.Push(c.A);"); return d;
            case 0x37: E("b.Push(c.B);"); return d;
            case 0x39: d.FallsThrough = false; E("return b.Pull16();"); return d;   // RTS
            case 0x3B:                                                           // RTI
                d.FallsThrough = false;
                E("c.CC = (byte)(b.Pull() | 0xC0); c.B = b.Pull(); c.A = b.Pull(); c.X = b.Pull16();");
                E("return b.Pull16();");
                return d;
            case 0x3E:                                                           // WAI: stack, then stop until an interrupt
                d.FallsThrough = false;
                E($"b.PushAll(0x{next():X4}); c.Waiting = true;");
                E($"return 0x{next():X4};");
                return d;
            case 0x3F:                                                           // SWI
                d.FallsThrough = false;
                E($"b.PushAll(0x{next():X4}); c.CC |= 0x10;");
                E("return b.Read16(0xFFFA);");
                return d;
            case 0x8D:                                                           // BSR
                d.Length = 2;
                d.FallsThrough = false;
                E($"b.Push16(0x{next():X4});");
                E(GoTo(next() + (sbyte)B(1)));
                return d;
            case 0xAD:                                                           // JSR n,X
                d.Length = 2;
                d.FallsThrough = false;
                E($"ea = (ushort)(c.X + 0x{B(1):X2}); b.Push16(0x{next():X4});");
                E("return (ushort)ea;");
                return d;
            case 0xBD:                                                           // JSR ext
                d.Length = 3;
                d.FallsThrough = false;
                E($"b.Push16(0x{next():X4});");
                E(GoTo(W(1)));
                return d;
            case 0x6E:                                                           // JMP n,X
                d.Length = 2;
                d.FallsThrough = false;
                E($"return (ushort)(c.X + 0x{B(1):X2});");
                return d;
            case 0x7E:                                                           // JMP ext
                d.Length = 3;
                d.FallsThrough = false;
                E(GoTo(W(1)));
                return d;
        }

        int hi = op >> 4, lo = op & 0x0F;
        if (hi == 0x2)                                                           // branches
        {
            d.Length = 2;
            int target = next() + (sbyte)B(1);
            if (lo == 0) { d.FallsThrough = false; E(GoTo(target)); }
            else E($"if (Branch(c.CC, 0x{lo:X})) {GoTo(target)}");
            return d;
        }
        if (hi is 0x4 or 0x5)                                                    // A / B unary
        {
            string r = hi == 0x4 ? "c.A" : "c.B";
            E(lo == 0xD ? $"Unary(ref c.CC, 0xD, {r});" : $"{r} = Unary(ref c.CC, 0x{lo:X}, {r});");
            return d;
        }
        if (hi is 0x6 or 0x7)                                                    // memory unary
        {
            string ea = hi == 0x6 ? $"(ushort)(c.X + 0x{B(1):X2})" : $"0x{W(1):X4}";
            d.Length = hi == 0x6 ? 2 : 3;
            E($"ea = {ea};");
            E(lo == 0xD ? "Unary(ref c.CC, 0xD, b.Read((ushort)ea));" : $"b.Write((ushort)ea, Unary(ref c.CC, 0x{lo:X}, b.Read((ushort)ea)));");
            return d;
        }
        Accumulator(d, op, hi, lo, B, W, E);
        return d;
    }

    private static void Accumulator(Insn d, byte op, int hi, int lo, Func<int, byte> B, Func<int, int> W, Action<string> E)
    {
        int mode = hi & 3;                                                       // 0 imm, 1 dir, 2 idx, 3 ext
        string acc = hi >= 0xC ? "c.B" : "c.A";
        bool isB = hi >= 0xC;
        bool wide = lo is 0xC or 0xE or 0xF;
        d.Length = mode switch { 0 => wide ? 3 : 2, 3 => 3, _ => 2 };
        string ea = mode switch
        {
            1 => $"0x{B(1):X2}",
            2 => $"(ushort)(c.X + 0x{B(1):X2})",
            _ => $"0x{W(1):X4}",
        };
        string Operand8() => mode == 0 ? $"0x{B(1):X2}" : $"b.Read({ea})";
        string Operand16() => mode == 0 ? $"0x{W(1):X4}" : $"b.Read16({ea})";
        switch (lo)
        {
            case 0xC: E($"Cpx(ref c.CC, c.X, {Operand16()});"); return;          // CPX
            case 0xE:                                                            // LDS / LDX
            {
                string r = isB ? "c.X" : "c.SP";
                E($"{r} = {Operand16()}; Logic16(ref c.CC, {r});");
                return;
            }
            case 0xF:                                                            // STS / STX
            {
                string r = isB ? "c.X" : "c.SP";
                E($"b.Write16({ea}, {r}); Logic16(ref c.CC, {r});");
                return;
            }
            case 0x7: E($"b.Write({ea}, {acc}); Logic(ref c.CC, {acc});"); return;   // STA
        }
        string m = Operand8();
        E(lo switch
        {
            0x0 => $"{acc} = Sub(ref c.CC, {acc}, {m}, false);",
            0x1 => $"Sub(ref c.CC, {acc}, {m}, false);",
            0x2 => $"{acc} = Sub(ref c.CC, {acc}, {m}, true);",
            0x4 => $"{acc} &= {m}; Logic(ref c.CC, {acc});",
            0x5 => $"Logic(ref c.CC, (byte)({acc} & {m}));",
            0x6 => $"{acc} = {m}; Logic(ref c.CC, {acc});",
            0x8 => $"{acc} ^= {m}; Logic(ref c.CC, {acc});",
            0x9 => $"{acc} = Add(ref c.CC, {acc}, {m}, true);",
            0xA => $"{acc} |= {m}; Logic(ref c.CC, {acc});",
            _ => $"{acc} = Add(ref c.CC, {acc}, {m}, false);",
        });
    }

    private sealed class ImageBus(byte[] mem) : IBus6800
    {
        public byte Read(ushort a) => mem[a];
        public void Write(ushort a, byte v) { }
    }
}
